_COMPILED = [(name, re.compile(pattern, re.I), search) for name, pattern, search in _TYPES]


def food_type(name: str | None, category: str | None = None) -> str | None:
    """상품명으로 품목을 정하고, 모르면 분류 경로로 정한다(분류가 '도시락'인 파스타는 면). 모르면 None."""
    for text in (name, category):
        flat = re.sub(r"\s+", "", text or "")
        for kind, pattern, _ in _COMPILED:
            if pattern.search(flat):
                return kind
    return None


def type_search_terms(kind: str) -> tuple[str, ...]:
    """같은 품목(대체품 포함) 후보를 이름으로 더 찾을 때 쓰는 검색어."""
    return next((search for name, _, search in _COMPILED if name == kind), ())


# 품목을 모를 때 '같은 상품군'으로 볼 공통 단어에서 빼는 말(용량·포장·판매 문구).
_GENERIC = re.compile(r"^(?:\d.*|[a-z]{1,2}|개입|묶음|박스|세트|선물|증정|무료배송|국내산|대용량)$", re.I)


def same_kind(query_kind: str | None, name: str, category: str | None, query_words: list[str]) -> bool:
    """후보가 보고 있는 식품과 같은 품목인가. 품목을 모르면 핵심 단어가 상품명에 들어 있어야 같은 품목으로 본다."""
    if query_kind is not None:
        return food_type(name, category) == query_kind
    flat = re.sub(r"\s+", "", name or "").lower()
    return any(w.lower() in flat for w in query_words if len(w) >= 2 and not _GENERIC.match(w))
